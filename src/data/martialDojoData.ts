export function getDojoProfile(artId: string): MartialDojoProfile {
  return MARTIAL_DOJO_PROFILES[artId] || MARTIAL_DOJO_PROFILES.karate
}

export function getDojoBenchmarkLevel(benchmarkId: string, defaultLevel = 1): number {
  if (typeof window === 'undefined') return defaultLevel
  try {
    const raw = localStorage.getItem('kiai_dojo_benchmarks')
    if (raw) {
      const parsed = JSON.parse(raw)
      if (typeof parsed[benchmarkId] === 'number') return parsed[benchmarkId]
    }
  } catch {}
  return defaultLevel
}

export function setDojoBenchmarkLevel(benchmarkId: string, level: number): void {
  if (typeof window === 'undefined') return
  try {
    const raw = localStorage.getItem('kiai_dojo_benchmarks')
    const parsed = raw ? JSON.parse(raw) : {}
    parsed[benchmarkId] = level
    localStorage.setItem('kiai_dojo_benchmarks', JSON.stringify(parsed))
  } catch {}
}

/** Converts a science-based Dojo Routine into a fully playable Kata */
export function dojoRoutineToKata(goal: DojoRoutineGoal, artName: string, artId: string): Kata {
  const items: WorkoutItem[] = goal.exercises.map((ex) => ({
    slug: ex.slug,
    duration: ex.duration,
    phase: ex.phase,
    pnf: ex.pnf,
    note: ex.note,
  }))

  return {
    uuid: `dojo-routine-${goal.id}`,
    name: goal.title,
    subtitle: `${artName} · ${goal.subtitle}`,
    symbol: goal.symbol || 'figure.martial.arts',
    tint: (goal.accent.replace(/var\(--|\)/g, '') as any) || 'ember',
    isPremade: true,
    premadeKey: goal.id,
    art: artId,
    difficulty: goal.difficulty || 'intermediate',
    restSeconds: null,
    createdAt: Date.now(),
    updatedAt: Date.now(),
    lastPerformedAt: null,
    items,
  }
}
